#!/usr/bin/env python3
"""Write a CS Brass instrument's decoded numbers as a `section.styx` overlay.

    python3 csb_instrument_spec.py <_ksp/CSB <instrument> dir> > "_patches/<label>/section.styx"

The brass counterpart of css_section_spec.py / csw_instrument_spec.py; every
number and KSP line is in tests/csb_spec_requirements.md:

- bodies / releases: the CC1 group curves of the strings slots CSB fills
  (vibsus = Sus, tremolo = Mutesus / Stoppedsus, harmonics = Flutter, …),
  layers named by the dynamics their recordings carry;
- shorts: velocity bands and dB (Repetitions' band COUNT in %ktuur[0]),
  random round robins avoiding the key's last 1 or 2; Rips one band;
- legato: no overlap delay; the whole transition model per instrument —
  the per-layer body handoff %k1aqh (wait / fade by velocity zone), the
  high-key override, old-body fades, LT offsets, previous-LT retire by
  attack class, the IOI dip and the LT fade-out curve %jygjv;
- marcato: hard = velocity >= 64 with no IOI term; the soft class's LT
  offset and level (by-class tables need the B6 mechanism — not yet).
"""
import csv, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import css_section_spec as css  # noqa: E402
import csw_instrument_spec as csw  # noqa: E402

MICS = ("Mix", "Main", "Room", "Close")
csw.MICS = MICS

# articulation -> (group prefix, CCs); the first recorded alternative wins
BODY_GROUPS = [
    ("Sus", "vibsus", (1,)),
    ("Leg", "legato", (1,)),
    ("Legzero", "legato zero", (1,)),
    ("Marcato", "marcato mod", (1,)),
    ("Mutesus", "tremolo", (1,)),
    ("Stoppedsus", "tremolo", (1,)),
    ("Flutter", "harmonics", (1,)),
    ("HTrills", "trills", (1,)),
    ("WTrills", "trills", (1,)),
]
RELEASE_GROUPS = [
    ("Susrel", "vibsus rel"),
    ("Mutesusrel", "tremolo rel"),
    ("Stoppedsusrel", "tremolo rel"),
    ("Fluttrel", "harmonics rel"),
    ("HTrel", "half trills rel"),
    ("WTrel", "whole trills rel"),
    ("Marcrel", "marcato mod rel"),
]
# short -> (file articulation, group family, thresholds, dB, %ktuur slot, avoid last N)
SHORTS = [
    ("Repetitions", "Repetitions", "spiccato", "%g1qri", "%bcez1", 0, 2),
    ("Staccatissimo", "Staccatissimo", "staccatissimo", "%aoywv", "%ak5pm", 1, 2),
    ("Staccato", "Staccato", "staccato", "%nfxdy", "%opj4y", 2, 1),
    ("Sfz", "Sfz", "sfz", "%cjzwd", "%5u3ic", 3, 1),
    ("Mutereps", "Mutereps", "pizzicato", "%n4f4k", "%pyntp", 4, 1),
    # 4 Horns: its stopped recordings play as the mute slot (slot_relabel.py)
    ("Mutereps", "Stoppedreps", "pizzicato", "%n4f4k", "%pyntp", 4, 1),
]
LAYER_GROUPS = ("p", "mf", "f", "ff")  # %k1aqh slots = the vibsus groups


def padded(pers, var, n):
    """persistent_1.tsv drops an array's trailing zeros: pad to its size."""
    v = list(pers.get(var, []))
    return v + [0] * (n - len(v))


# Kontakt's level over the raw file per instrument, null-tested (Kontakt minus
# ours on the probe's held notes, + the library's 2.55): the NKI's instrument
# volume, which the decoder does not read yet. Solos sit at ×2 (+6.02 dB),
# the sections at ×4 (+12.04).
INSTRUMENT_GAIN_DB = {
    "CSB Solo Trumpet": 6.02, "CSB Solo Horn": 5.93, "CSB Solo Trombone": 5.13,
    "CSB Solo Tuba": 6.03, "CSB Solo Bass Trombone": 6.05,
    "CSB 2 Trumpets": 11.86, "CSB 4 Horns": 11.92, "CSB 2 Trombones": 12.11,
}


def main():
    d = sys.argv[1]
    pers = css.persistent(d)
    all_groups = json.load(open(os.path.join(d, "groups.json")))
    groups = {g["name"][4:]: g for g in all_groups if g["name"].startswith("Mix ")}
    gnames = {i: g["name"] for i, g in enumerate(all_groups)}
    zones = list(csv.DictReader(open(os.path.join(d, "zones.tsv")), delimiter="\t"))
    print(f"// Generated by csb_instrument_spec.py from {os.path.basename(os.path.normpath(d))} — do not edit.")
    # decoded (program volume x Mix bus fader x its gain stage), else the
    # measured table
    gain = css.instrument_gain_db(d)
    if gain is None:
        gain = INSTRUMENT_GAIN_DB.get(os.path.basename(os.path.normpath(d)))
    if gain is not None:
        print(f"instrument_gain_db {gain}")
    pan = css.instrument_pan(d)
    if pan:
        print(f"instrument_pan {pan}")
    print("articulations (")
    done = set()
    for aid, prefix, ccs in BODY_GROUPS:
        if prefix in done and aid in ("Stoppedsus",):
            continue
        rec = csw.recorded_dynamics(zones, gnames, prefix, aid)
        cs = [(rec[dy], cc, pts) for dy, cc, pts in css.curves(groups, prefix, ccs, rel=False) if dy in rec]
        if cs:
            csw.emit_curves(aid, cs, list(dict.fromkeys(dy for dy, _, _ in cs)),
                            csw.layer_fx(d, all_groups, prefix, rec))
            if prefix == "tremolo":
                done.add(prefix)
    done.clear()
    for aid, prefix in RELEASE_GROUPS:
        if prefix in done:
            continue
        rec = csw.recorded_dynamics(zones, gnames, prefix, aid)
        cs = [(rec[dy], cc, pts) for dy, cc, pts in css.curves(groups, prefix, (), rel=True) if dy in rec]
        if cs:
            csw.emit_curves(aid, cs, list(dict.fromkeys(dy for dy, _, _ in cs)),
                            csw.layer_fx(d, all_groups, prefix, rec))
            if prefix == "tremolo rel":
                done.add(prefix)

    ktuur = padded(pers, "%ktuur", 6)
    for aid, fa, family, tvar, dvar, slot, avoid in SHORTS:
        th, db_ = pers.get(tvar), pers.get(dvar)
        dyns, rr = csw.short_layers(zones, gnames, fa, family)
        if not th or not db_ or not dyns:
            continue
        # slot 0 holds the band COUNT; the others a 0/1 "four bands" flag
        nb = ktuur[0] if slot == 0 else (4 if ktuur[slot] == 1 else 3)
        nb = max(1, min(nb, len(dyns)))
        print(f"    {{\n        id {aid}")
        print(f"        dynamics ({' '.join(dyns[:nb])})")
        print(f"        rr {rr}")
        print(f"        vel_thresholds ({' '.join(map(str, th[1:nb]))})")
        print(f"        vel_layer_db ({' '.join(map(str, padded(pers, dvar, nb)[:nb]))})")
        print(f"        rr_random_avoid_last {min(avoid, max(rr - 1, 0))}")
        css.emit_key_pitch(css.key_pitch_cents(all_groups, family))
        css.emit_amp_env(css.short_amp_env(all_groups, family, pers))
        print("    }")
    # muted shorts draw a random detune only where the patch enables it
    # (`$5xze0`; KSP 12794: ±$aolsn c unless the key struck within $s01mu ms)
    if pers.get("$5xze0", [0])[0] == 1:
        print("    {\n        id Mutereps")
        print(f"        random_tune_cents {css.one(pers, '$aolsn')}")
        print(f"        random_tune_gate_ms {css.one(pers, '$s01mu')}")
        print("    }")
    rips(pers, zones, gnames)
    marcato(pers, marcato_lt_layers(zones, gnames))
    held_detune(pers)
    taka_phrase(pers)
    release_levels(pers)
    print(")")
    legato(pers, groups, zones, gnames)


# the release-volume slot (`$se4l4`) of each body articulation
RELEASE_SLOTS = {
    "Sus": 0, "Mutesus": 2, "Stoppedsus": 2, "HTrills": 3, "WTrills": 3, "Flutter": 4, "Marcato": 5,
}


def release_levels(pers):
    """The release level by held time, per context (on release 17361-17849):
    3-point detached / first and phrase-end tables, a 4-point in-phrase one,
    `%nuvn3` = no in-phrase release past its last point; deci-dB."""
    ab, ab_db = padded(pers, "%ciooq", 18), padded(pers, "%54rxx", 18)
    ip, ip_db = padded(pers, "%x1kwp", 24), padded(pers, "%5gm34", 24)
    pe, pe_db = padded(pers, "%e1dvv", 18), padded(pers, "%fxjmy", 18)
    cut = padded(pers, "%nuvn3", 6)
    trim = css.one(pers, "$b5zq1") / 10

    def curve(t, d, slot, n):
        ts = " ".join(css.fmt(v) for v in t[slot * n:slot * n + n])
        ds = " ".join(css.fmt(v / 10) for v in d[slot * n:slot * n + n])
        return f"{{ thresholds_ms ({ts}), anchors_ms ({ds}) }}"

    for aid, slot in RELEASE_SLOTS.items():
        print(f"    {{\n        id {aid}")
        print("        release_by_held {")
        print(f"            detached    {curve(ab, ab_db, slot, 3)}")
        print(f"            detached_db {css.fmt(trim)}")
        print(f"            first       {curve(ab, ab_db, slot, 3)}")
        print(f"            in_phrase   {curve(ip, ip_db, slot, 4)}")
        if cut[slot] == 1:
            print(f"            in_phrase_cutoff_ms {css.fmt(ip[slot * 4 + 3])}")
        print(f"            phrase_end  {curve(pe, pe_db, slot, 3)}")
        print("        }")
        print("    }")


def rips(pers, zones, gnames):
    """Rips: one band, `%tccxl[0]` dB at velocity 1, RR by key only."""
    rrs = set()
    for z in zones:
        if gnames.get(int(z["group"])) != "Mix col legno":
            continue
        parts = csw.name_parts(z["sample"])
        if len(parts) >= 3 and parts[1] == "Rips":
            rrs.add(parts[-1])
    if not rrs:
        return
    rr = len(rrs)
    print("    {\n        id Rips")
    print("        dynamics ()")  # rips have no dynamic: key and RR only
    print(f"        rr {rr}")
    print("        vel_thresholds ()")
    print(f"        vel_layer_db ({padded(pers, '%tccxl', 1)[0]})")
    print(f"        rr_random_avoid_last {min(1, rr - 1)}")
    print("    }")


# a group's dynamic code (`$tylrz`): the marc leg layer plays with the
# marcato mod layer of the same code
DYN_CODE = {"p": 1, "mf": 2, "f": 3, "ff": 4, "fff": 4}


def marcato_lt_layers(zones, gnames, leg="Leg"):
    """`lt_layers`: each `marc leg <x>` group with the `marcato mod <y>` of its
    dynamic code, named by the recordings each holds (a marcato group that
    holds a Sus recording, not a Marcato, has no marcato layer to pair)."""
    def held(prefix, artic):
        out = {}
        for code_name in DYN_CODE:
            rec = {}
            for z in zones:
                if gnames.get(int(z["group"])) != f"Mix {prefix} {code_name}":
                    continue
                parts = csw.name_parts(z["sample"])
                if len(parts) > 3 and parts[1] == artic:
                    rec[parts[3]] = rec.get(parts[3], 0) + 1
            if rec:
                out[DYN_CODE[code_name]] = max(rec, key=rec.get)
        return out
    legs, marcs = held("marc leg", leg), held("marcato mod", "Marcato")
    return [(marcs[c], legs[c]) for c in sorted(legs) if c in marcs]


def marcato(pers, lt_layers):
    p = lambda v: css.one(pers, v)  # noqa: E731
    print("    {\n        id Marcato")
    print("        marcato_transition {")
    # hard = velocity >= $kxbiw, no IOI term (the engine tests velocity > hard_velocity)
    print(f"            hard_velocity {p('$kxbiw') - 1}")
    print("            hard_ioi_ms 0")
    print(f"            xfade_ms {p('$a3zg3')}")  # the swell's XTime, per instrument
    print(f"            body_offset_ms ({p('$yp2sq')} {p('$yp2sq')})")
    # past an octave too: $1fvjk := $yp2sq on every connection (KSP 12955)
    print(f"            body_offset_big_ms ({p('$yp2sq')} {p('$yp2sq')})")
    # LT offset, level and previous-LT retire by attack class (soft, hard)
    print(f"            lt_offset_ms_by_class ({p('$5ibvn')} {p('$cblef')})")
    print(f"            lt_db_by_class ({css.fmt(p('$b23jt') / 10)} {css.fmt(p('$rlbmz') / 10)})")
    print(f"            lt_retire_ms_by_class ({p('$pprfd')} {p('$orqo1')})")
    if lt_layers:
        pairs = " ".join(f"{{dynamic {m}, lt_dynamic {l}, gain_index 0}}" for m, l in lt_layers)
        print(f"            lt_layers ({pairs})")
    print("        }")
    print("    }")


def taka_phrase(pers):
    """The Taka phrase's per-instrument numbers (see the library spec's Taka
    `phrase`): the chord time $nh2j5, the tick 15000000 / $acd3t us, the
    fade $x53g2, the velocity bands %hneka and levels %z4pdd."""
    bpm, delay, fade = (css.one(pers, v) for v in ("$acd3t", "$nh2j5", "$x53g2"))
    th, db = pers.get("%hneka"), pers.get("%z4pdd")
    if not bpm or delay is None or fade is None or not th or not db:
        return
    tick = 15000000 // int(bpm) / 1000
    print("    {\n        id Taka")
    print(f"        vel_thresholds ({th[1]} {th[2]})")
    print(f"        vel_layer_db ({db[0]} {db[1]} {db[2]})")
    print("        phrase {")
    print(f"            delay_ms  {delay}")
    print(f"            tick_ms   {tick:g}")
    print(f"            fade_ms   {fade}")
    print("            first_rr  (1 2 3)")
    print("            second_rr (4 6 8 10 12 14 16 18 20)")
    print("            step_wrap (4 21)")
    print("            end_rr    (22 23 24)")
    print("        }")
    print("    }")


def held_detune(pers):
    """A body struck while another key is down detunes by random(-$yqdot,
    $yqdot) cents when `$q4ous` is on (KSP 11050-11071) — inside `if
    ($ra4sw=0)` (KSP 9514), the chord-mode path only. Sus plays in legato
    mode (%crp0r[0] = 1), so its legato bodies never detune (giving Sus the
    draw left every brass legato pair decorrelated: Solo Bass Trombone
    -0.0 dB); Marcato's connected strikes do."""
    if not css.one(pers, "$q4ous"):
        return
    for aid in ("Marcato",):
        print(f"    {{\n        id {aid}")
        print(f"        held_random_tune_cents {css.one(pers, '$yqdot')}")
        print("    }")


def handoff(arr, zones, gnames):
    """`body_handoff` entries from a %k1aqh-shaped array (slot*20: big wait,
    +1..3 wait by zone, +4 big fade, +5..7 fade by zone)."""
    out = []
    for slot, gdyn in enumerate(LAYER_GROUPS):
        rec = csw.recorded_dynamics(zones, gnames, "vibsus", "Sus")
        if gdyn not in rec:
            continue
        b = slot * 20
        wait = arr[b + 1 : b + 4]
        fade = arr[b + 5 : b + 8]
        out.append(
            f"            {{ dynamic {rec[gdyn]}, wait_ms ({' '.join(map(str, wait))}), "
            f"fade_ms ({' '.join(map(str, fade))}), big_fade_ms {arr[b + 4]} }}"
        )
    return out


def legato(pers, groups, zones, gnames):
    p = lambda v: css.one(pers, v)  # noqa: E731
    k1aqh = padded(pers, "%k1aqh", 80)
    wu5b4 = padded(pers, "%wu5b4", 80)
    flex = css.flex(groups, "legato") or []
    curve = [v - 100 for v in padded(pers, "%jygjv", 100)[:100]]
    big_fade = k1aqh[3 * 20 + 4] or k1aqh[4]
    print("legato {")
    print("    overlap_delay {")  # CSB has none
    for mode in ("low_latency", "expressive"):
        print(f"        {mode} {{")
        for side in ("soft", "loud"):
            print(f"            {side} {{ thresholds_ms (0), anchors_ms (0) }}")
        print("        }")
    print("    }")
    lt = f"({p('$k2afl')} {p('$xem4t')} {p('$yds0m')})"
    print(f"    lt_offset_expressive {lt}")
    print(f"    lt_offset_low_latency {lt}")
    print("    kontakt_transition {")
    print(f"        old_body_fade_ms {p('$mhmq3')}")
    print(f"        old_body_fade_by_zone_ms ({p('$mhmq3')} {p('$qkgxg')} {p('$yn5xm')})")
    print(f"        body_wait_ms {k1aqh[3 * 20 + 1]}")
    print(f"        body_fade_ms {k1aqh[3 * 20 + 5]}")
    print(f"        big_leap_body_offset_ms {p('$p3wmm')}")
    print(f"        big_leap_old_fade_ms {p('$1qyra')}")
    print(f"        big_leap_new_fade_ms {big_fade}")
    print("        in_phrase_release_db 0")
    # the old note's release starts after the transition (null test, CSB Solo
    # Trumpet: Kontakt's in-phrase release 5.7 ms behind ours)
    print("        in_phrase_release_delay_ms 5.7")
    seg0 = flex[0][0] if flex else 0
    print(f"        lt_seg0_ms_low_latency {seg0}")
    print(f"        lt_seg0_ms_expressive {seg0}")
    env = " ".join(
        f"{{time_ms {css.fmt(float(t))}, level {css.fmt(float(l))}, curve {css.fmt(float(c))}}}" for t, l, c in flex[1:]
    )
    print(f"        lt_env ( {env} )")
    # the envelope's first node is the group flex's first level (CC67 25 in
    # legato sustain; no IOI law as in CSS): CC66 127 x CC67 = level x 127
    node = css.fmt(float(flex[0][1]) * 127) if flex else "127"
    print("        lt_node {")
    for mode in ("expressive", "low_latency"):
        print(f"            {mode} {{ cc66 {{ thresholds_ms (0), anchors_ms (127) }}, cc67 {{ thresholds_ms (0), anchors_ms ({node}) }} }}")
    print("        }")
    print("        phrase_dip_db 0")
    print("        phrase_dip_window_ms 0")
    print("        lt_retire {")
    print(f"            low_latency {{ thresholds_ms (150 300), anchors_ms ({p('$w4sb3')} {p('$elc3z')}) }}")
    print(f"            expressive {{ thresholds_ms (150 300), anchors_ms ({p('$w4sb3')} {p('$elc3z')}) }}")
    print(f"            loud {{ thresholds_ms (150 300), anchors_ms ({p('$h3l3o')} {p('$4wrso')}) }}")
    print("            loud_from_zone 2")
    print("        }")
    print("        body_handoff (")
    print("\n".join(handoff(k1aqh, zones, gnames)))
    print("        )")
    print("        retrigger_body_handoff (")
    print("\n".join(handoff(wu5b4, zones, gnames)))
    print("        )")
    if p("$vv4qt") < 127:
        print(f"        high_key_handoff {{ min_key {p('$vv4qt')}, wait_ms {p('$so0i3')}, fade_ms {p('$kk5ih')} }}")
    print(f"        lt_fade_curve_db ({' '.join(css.fmt(float(v)) for v in curve)})")
    dip = (
        f"thresholds_ms ({p('$xdpcr')} {p('$0crpu')} {p('$lgkxr')} {p('$fca5r')}), "
        f"anchors_ms (0 {css.fmt(p('$x3vds') / 10)} {css.fmt(p('$4jko3') / 10)} 0)"
    )
    print(f"        lt_ioi_dip {{ db {{ {dip} }}, recover_ms {p('$pgocp')} }}")
    print("    }")
    print("}")


if __name__ == "__main__":
    main()
