/// `[drive, makeup, wet]` at a saved shape (−1..=1), linear between rows.
#[must_use]
pub fn enhanced_at(shape: f32) -> [f32; 3] {
    let last = ENHANCED.len() - 1;
    if shape.is_nan() {
        return [1.0, 1.0, 0.0];
    }
    let at = (shape.clamp(-1.0, 1.0) + 1.0) * 0.5 * last as f32;
    let i = (at as usize).min(last - 1);
    let f = at - i as f32;
    let (a, b) = (ENHANCED[i], ENHANCED[i + 1]);
    std::array::from_fn(|n| (b[n] - a[n]) * f + a[n])
}

/// One sample through Enhanced at `[drive, makeup, wet]`.
#[inline]
#[must_use]
pub fn enhanced(x: f32, [drive, makeup, wet]: [f32; 3]) -> f32 {
    let u = (drive * x).clamp(-8.0, 8.0);
    wet * (makeup * u * (1.0 - u.abs() * 0.0625) - x) + x
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_ends_and_the_drive_law() {
        assert_eq!(ENHANCED[0], [1.0, 1.0, 0.0]);
        for (i, r) in ENHANCED.iter().enumerate() {
            let law = 100f32.powf(i as f32 / 127.0);
            assert!((r[0] / law - 1.0).abs() < 0.001, "{i}: {} vs {law}", r[0]);
        }
        // shape −1 is position 0: no drive, dry
        assert_eq!(enhanced(0.5, enhanced_at(-1.0)), 0.5);
    }
}
